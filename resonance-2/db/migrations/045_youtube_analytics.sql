-- YouTube analytics. Number 045.
-- 044 seeded Future Ideas. This file stores the owner Google connection,
-- daily channel numbers, per-video numbers, pull outcomes, and the latest
-- health-check mark the YouTube pull reads.
-- refresh_token stays in youtube_oauth. Page and JSON reads do not select it.
-- Idempotent: CREATE is IF NOT EXISTS. A second run changes nothing.

CREATE TABLE IF NOT EXISTS youtube_oauth (
  id integer PRIMARY KEY CHECK (id = 1),
  refresh_token text NOT NULL,
  channel_id text,
  channel_title text,
  subscriber_count bigint,
  video_count bigint,
  connected_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS youtube_channel_days (
  day date PRIMARY KEY,
  views bigint,
  watch_time_minutes numeric,
  avg_view_duration_seconds numeric,
  pulled_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS youtube_videos (
  video_id text PRIMARY KEY,
  title text NOT NULL DEFAULT '',
  views bigint,
  watch_time_minutes numeric,
  avg_view_percentage numeric,
  impressions bigint,
  ctr numeric,
  likes bigint,
  comments bigint,
  window_start date,
  window_end date,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS youtube_video_days (
  video_id text NOT NULL REFERENCES youtube_videos (video_id) ON DELETE CASCADE,
  day date NOT NULL,
  views bigint,
  watch_time_minutes numeric,
  avg_view_percentage numeric,
  impressions bigint,
  ctr numeric,
  likes bigint,
  comments bigint,
  pulled_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (video_id, day)
);

CREATE INDEX IF NOT EXISTS youtube_video_days_day_idx ON youtube_video_days (day);

CREATE TABLE IF NOT EXISTS youtube_pulls (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot text NOT NULL,
  started_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL CHECK (status IN ('ok', 'skipped', 'error')),
  message text NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS youtube_pulls_started_idx ON youtube_pulls (started_at DESC);

CREATE TABLE IF NOT EXISTS health_check_marks (
  id integer PRIMARY KEY CHECK (id = 1),
  ok boolean NOT NULL,
  checked_at timestamptz NOT NULL
);
