-- Printer ink snapshots from the HP OfficeJet Pro 9120e. Number 047.
-- 046 stores Factorio snapshots. This file does not change those tables.
-- Each post is kept. The node reads the newest row.
-- The ingest token is stored only as a sha256 hex digest.
-- Idempotent: CREATE is IF NOT EXISTS. A second run inserts nothing.

CREATE TABLE IF NOT EXISTS printer_tokens (
  id integer PRIMARY KEY CHECK (id = 1),
  token_hash text NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS printer_snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  printer_model text,
  read_at timestamptz,
  received_at timestamptz NOT NULL DEFAULT now(),
  version text,
  supplies jsonb NOT NULL DEFAULT '[]'::jsonb,
  payload jsonb NOT NULL
);

CREATE INDEX IF NOT EXISTS printer_snapshots_received_idx
  ON printer_snapshots (received_at DESC, id DESC);
