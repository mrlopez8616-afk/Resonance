-- Nike Run Club runs posted with the nightly steps Shortcut.
-- Number 028. 026 is the roundtable. 027 seeds future ideas.
-- measure_key is the Chicago day plus distance and duration.
-- start_key is the Chicago day plus start when the shortcut sent a start.
-- A later post that matches either key updates this row.
-- Daily heart rate stays on fitness_metrics, one row per day.

CREATE TABLE IF NOT EXISTS fitness_nrc_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day date NOT NULL,
  start_time timestamptz,
  distance_mi numeric NOT NULL,
  duration_sec numeric NOT NULL,
  pace_sec_per_mi numeric,
  avg_hr numeric,
  start_key text,
  measure_key text NOT NULL,
  payload jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS fitness_nrc_runs_measure_idx
  ON fitness_nrc_runs (measure_key);

CREATE INDEX IF NOT EXISTS fitness_nrc_runs_start_idx
  ON fitness_nrc_runs (start_key);

CREATE INDEX IF NOT EXISTS fitness_nrc_runs_day_idx
  ON fitness_nrc_runs (day);
