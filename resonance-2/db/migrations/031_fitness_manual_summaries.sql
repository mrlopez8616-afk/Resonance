-- Manual fitness summaries. Number 031.
-- 030 is Chain Security. This file inserts no daily metrics and no runs.
-- fitness_manual_summaries never feeds fitness_metrics, fitness_workouts,
-- fitness_shortcut_workouts, or fitness_nrc_runs, and it never changes their totals.
-- The same period, app, and metric updates the row. A second post does not insert another.
-- approx is true when the figure was rounded. source defaults to manual-import.

CREATE TABLE IF NOT EXISTS fitness_manual_summaries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_date date NOT NULL,
  period_start date NOT NULL,
  period_end date NOT NULL,
  app text NOT NULL,
  metric text NOT NULL,
  value numeric NOT NULL,
  unit text NOT NULL,
  approx boolean NOT NULL DEFAULT false,
  note text,
  source text NOT NULL DEFAULT 'manual-import',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (period_start, period_end, app, metric)
);

CREATE INDEX IF NOT EXISTS fitness_manual_summaries_period_idx
  ON fitness_manual_summaries (period_end, period_start);
