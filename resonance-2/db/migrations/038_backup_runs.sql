-- Nightly backup log. Number 038.
-- 037 inserted the Fight Desk lesson. This file creates backup_runs
-- when that table is missing. It inserts no rows and deletes none.
-- A second run changes nothing.

CREATE TABLE IF NOT EXISTS backup_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at timestamptz NOT NULL,
  finished_at timestamptz,
  status text NOT NULL CHECK (status IN ('ok', 'error')),
  table_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
  byte_size bigint,
  object_count integer,
  prefix text,
  blob_status text CHECK (
    blob_status IS NULL OR blob_status IN ('copied', 'unavailable', 'empty')
  ),
  blob_note text,
  error text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS backup_runs_started_idx ON backup_runs (started_at DESC);
