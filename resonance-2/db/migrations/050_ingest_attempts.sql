-- Ingest attempt log for the two fitness posts. Number 050.
-- 049 stores broker reads. This file does not change those tables.
-- One row per request. The token, the header value, and the body are not stored.
-- The writer deletes rows older than 30 days. This file inserts nothing.
-- Idempotent: CREATE is IF NOT EXISTS. A second run changes nothing.

CREATE TABLE IF NOT EXISTS ingest_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route text NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  status_code integer NOT NULL,
  auth_ok boolean NOT NULL,
  reason text NOT NULL,
  user_agent text,
  content_length integer,
  rows_upserted integer
);

CREATE INDEX IF NOT EXISTS ingest_attempts_route_received_idx
  ON ingest_attempts (route, received_at);

CREATE INDEX IF NOT EXISTS ingest_attempts_received_idx
  ON ingest_attempts (received_at);
